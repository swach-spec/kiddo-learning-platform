// Lists every image under public/images so the app knows which pictures exist.
// Scenes, covers and avatars without a picture keep their emoji, so images can
// be added a few at a time. Runs automatically before `npm run dev` and `npm run build`.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = join(process.cwd(), "public");
const images = join(root, "images");
const found = [];
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else if (/\.(webp|png|jpe?g|avif)$/i.test(name)) found.push("/" + relative(root, full).split(sep).join("/"));
  }
}
walk(images);
found.sort();
const body = `// Generated by scripts/sync-media.mjs — do not edit by hand. Run \`npm run images\` after adding pictures.\nexport const MEDIA: ReadonlySet<string> = new Set<string>(${JSON.stringify(found, null, 2)});\n`;
writeFileSync(join(process.cwd(), "src", "content", "media-manifest.ts"), body);
console.log(`media manifest: ${found.length} image(s)`);
